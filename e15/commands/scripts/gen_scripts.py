"""Generate the workspace's script set (SPEC §5.6) into OUTDIR.

  burn_<ms>.py   touch 32 MiB of heap, then a FIXED amount of CPU work: <ms> x LOOPS_PER_MS
                 outer iterations, sized so the loop takes about <ms> on the laptop (Python 3.9).
                 The work is fixed and no clock is read, so contention shows up as a longer run
                 rather than less work. <ms> is nominal; calibration measures run_ms on the guest.
                 The interpreter class and the interpreter stand-in pick among them by run time.
  edit.py        an Edit-tool stand-in: N search-and-replace edits on one file, each written
                 back atomically (temp file + rename), as editors do.
  write_tree.py  a Write-tool stand-in at scale: N files of the project's own text.
  ps.py          a `ps -e`/`top -b` stand-in (the template has no procps): scans /proc,
                 optionally for several samples.

Usage: python3 gen_scripts.py OUTDIR
Stdlib only, Python 3.9+ (the guest's UBI 9 python3).
"""

import pathlib
import sys

BURN_MS = (50, 200, 1000, 5000, 20000)
HEAP_MIB = 32

# Outer iterations (1000 LCG steps each) per millisecond, measured 2026-11-01 on the laptop
# under /usr/bin/python3 3.9.6: 20.1-21.1 per ms. Changing it changes every burn's work.
LOOPS_PER_MS = 21

BURN = '''\
"""Generated by e15/commands/scripts/gen_scripts.py: burn_{ms} (nominal {ms} ms).

Touches {mib} MiB of heap, then runs a fixed {loops} x 1000 LCG steps. No clock is read.
"""


def work(loops):
    n = 0
    for _ in range(loops):
        for _ in range(1000):
            n = (n * 1103515245 + 12345) & 0x7FFFFFFF
    return n


heap = bytearray({mib} * 1024 * 1024)
for i in range(0, len(heap), 4096):
    heap[i] = 1
print("burn_{ms}", {loops}, work({loops}))
'''

EDIT = '''\
"""Generated by e15/commands/scripts/gen_scripts.py: edit.py FILE N."""
import os
import sys

path, n = sys.argv[1], int(sys.argv[2])
for k in range(n):
    with open(path) as f:
        text = f.read()
    text = text.replace("def ", "def  ", 1) if k % 2 == 0 else text.replace("def  ", "def ", 1)
    tmp = path + ".tmp"
    with open(tmp, "w") as f:
        f.write(text)
        f.flush()
        os.fsync(f.fileno())
    os.replace(tmp, path)
print("edit", path, n)
'''

WRITE_TREE = '''\
"""Generated by e15/commands/scripts/gen_scripts.py: write_tree.py SRC OUTDIR N."""
import os
import sys

src, out, n = sys.argv[1], sys.argv[2], int(sys.argv[3])
with open(src) as f:
    text = f.read()
os.makedirs(out, exist_ok=True)
for k in range(n):
    with open(os.path.join(out, "f%04d.py" % k), "w") as f:
        f.write("# %d\\n" % k)
        f.write(text)
print("write_tree", out, n)
'''

PS = '''\
"""Generated by e15/commands/scripts/gen_scripts.py: ps.py [SAMPLES [INTERVAL_S]]."""
import os
import sys
import time

samples = int(sys.argv[1]) if len(sys.argv) > 1 else 1
interval = float(sys.argv[2]) if len(sys.argv) > 2 else 0.0
proc = "/proc"
for s in range(samples):
    rows = []
    for pid in os.listdir(proc):
        if not pid.isdigit():
            continue
        try:
            with open(os.path.join(proc, pid, "stat")) as f:
                stat = f.read()
            # comm is in parentheses and may hold spaces or ')'; the fields after the LAST ')'
            # start at field 3 (state), so utime/stime (fields 14/15) are rest[11]/rest[12].
            comm = stat[stat.index("(") + 1:stat.rindex(")")]
            rest = stat[stat.rindex(")") + 1:].split()
            cpu = int(rest[11]) + int(rest[12])
            with open(os.path.join(proc, pid, "status")) as f:
                rss = next((l.split()[1] for l in f if l.startswith("VmRSS")), "0")
        except (OSError, ValueError, IndexError):
            continue
        rows.append((int(pid), comm, rest[0], cpu, rss))
    print("sample", s, "procs", len(rows))
    for row in sorted(rows):
        print("%7d %-20s %s %8d %8s" % row)
    if s + 1 < samples:
        time.sleep(interval)
'''


def main(argv):
    if len(argv) != 1:
        sys.exit("usage: gen_scripts.py OUTDIR")
    out = pathlib.Path(argv[0])
    out.mkdir(parents=True, exist_ok=True)
    for ms in BURN_MS:
        (out / f"burn_{ms}.py").write_text(
            BURN.format(ms=ms, mib=HEAP_MIB, loops=ms * LOOPS_PER_MS))
    (out / "edit.py").write_text(EDIT)
    (out / "write_tree.py").write_text(WRITE_TREE)
    (out / "ps.py").write_text(PS)


if __name__ == "__main__":
    main(sys.argv[1:])
